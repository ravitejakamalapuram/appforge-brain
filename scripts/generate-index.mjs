#!/usr/bin/env node
// Regenerates INDEX.md for decisions/, postmortems/, research/opportunities/ and experiments/,
// per appforge-ai-master-plan.md §9.2: "Generated INDEX.md (title, tags, one-line summary per
// file) + rg". Meant to run on every push (CI fails the build if the committed INDEX.md is stale
// — see .github/workflows/pr-checks.yml).
//
// decisions/ and postmortems/ are append-only (§9.1): once a record is committed, `summary` can
// never be edited, so a claim that a later record overturns keeps rendering in the index as if it
// were still current. `review_outcome` is one of the three fields the append-only check does let a
// record carry (scripts/validate-decisions.mjs APPEND_ONLY_EXEMPT_FIELDS), so it is the only place
// a correction can live. This generator therefore flags any row whose record has a
// `review_outcome`, so the index itself says "part of this was corrected" instead of leaving
// `status: reviewed` — which reads as "checked, fine" — as the only signal. The record is not
// touched; only the generated view changes.
//
// Usage:
//   node scripts/generate-index.mjs           # write the generated INDEX.md files
//   node scripts/generate-index.mjs --check   # exit 1 if any INDEX.md would change (CI mode)
//   add --json for a cli-output@1 line
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { parseFrontmatter } from './lib/frontmatter.mjs';
import { buildOutput, printOutput } from './lib/cli-output.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

// Prefixed to the summary cell (not appended) so a reader who skims the column hits the warning
// before the possibly-superseded claim, and so the summary's 200-char truncation can never eat it.
const CORRECTED_PREFIX = '\u26a0 **partly corrected** — see `review_outcome` in the record.';

const MARKER_START = '<!-- GENERATED by scripts/generate-index.mjs — do not edit by hand, edit the source files and re-run it -->';

const TARGETS = [
  { dir: 'decisions', kind: 'markdown' },
  { dir: 'postmortems', kind: 'markdown' },
  { dir: 'research/opportunities', kind: 'yaml' },
  { dir: 'experiments', kind: 'yaml' },
];

export function readMarkdownEntry(filePath) {
  const content = readFileSync(filePath, 'utf8');
  const { data } = parseFrontmatter(content);
  return {
    file: path.basename(filePath),
    id: data.id ?? path.basename(filePath, '.md'),
    title: data.title ?? '(untitled)',
    tags: Array.isArray(data.tags) ? data.tags : [],
    summary: data.summary ?? data.decision ?? data.reason ?? '',
    status: data.status,
    reviewOutcome: data.review_outcome ?? null,
  };
}

export function readYamlEntry(filePath) {
  const content = readFileSync(filePath, 'utf8');
  const data = yaml.load(content) ?? {};
  return {
    file: path.basename(filePath),
    id: data.id ?? path.basename(filePath, path.extname(filePath)),
    title: data.title ?? '(untitled)',
    tags: Array.isArray(data.tags) ? data.tags : [],
    summary: data.summary ?? '',
    status: data.status,
    reviewOutcome: data.review_outcome ?? null,
  };
}

function collectEntries(dir, kind) {
  const abs = path.join(ROOT, dir);
  if (!existsSync(abs)) return [];
  const exts = kind === 'markdown' ? ['.md'] : ['.yaml', '.yml'];
  const files = readdirSync(abs)
    .filter((f) => exts.includes(path.extname(f)) && f !== 'INDEX.md')
    .sort();
  return files.map((f) => (kind === 'markdown' ? readMarkdownEntry(path.join(abs, f)) : readYamlEntry(path.join(abs, f))));
}

export function renderIndex(dir, entries) {
  const lines = [MARKER_START, '', `# ${dir}/ index`, ''];
  if (entries.length === 0) {
    lines.push('_No entries yet._', '');
  } else {
    lines.push('| ID | Title | Tags | Status | Summary |', '|---|---|---|---|---|');
    for (const e of entries) {
      const tags = e.tags.length ? e.tags.map((t) => `\`${t}\``).join(' ') : '—';
      const summary = (e.summary || '').replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 200);
      const status = e.status ?? '—';
      const cell = e.reviewOutcome ? `${CORRECTED_PREFIX} ${summary}`.trim() : summary;
      lines.push(`| [${e.id}](./${e.file}) | ${e.title} | ${tags} | ${status} | ${cell} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function generateAll() {
  return TARGETS.map(({ dir, kind }) => {
    const entries = collectEntries(dir, kind);
    return { dir, content: renderIndex(dir, entries), entryCount: entries.length };
  });
}

function main() {
  const args = process.argv.slice(2);
  const checkMode = args.includes('--check');
  const jsonFlag = args.includes('--json');

  const generated = generateAll();
  const stale = [];

  for (const { dir, content } of generated) {
    const indexPath = path.join(ROOT, dir, 'INDEX.md');
    const existing = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : null;
    if (existing === content) continue;
    if (checkMode) {
      stale.push(dir);
    } else {
      writeFileSync(indexPath, content, 'utf8');
    }
  }

  const command = checkMode ? 'generate-index --check' : 'generate-index';
  const ok = checkMode ? stale.length === 0 : true;
  const errors = stale.map((d) => `${d}/INDEX.md is stale — run \`node scripts/generate-index.mjs\` and commit the result`);
  const output = buildOutput(command, ok, { foldersChecked: generated.length, stale }, errors);
  printOutput(output, jsonFlag);
  process.exit(ok ? 0 : 1);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
